#include<iostream>
using namespace std;

int main() {
    // C++11 version
    auto a = 10;
    auto b = 3.4;
    auto c = "AAmani";
    auto d = 'A';

    cout << "a = " << a << endl;
    cout << "b = " << b << endl;
    cout << "c = " << c << endl;
    cout << "d = " << d << endl;

    return 0;
}
